'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const {Script}=require('node:vm');
const friends=fs.readFileSync('friends.html','utf8');
const settings=fs.readFileSync('settings-surface.js','utf8');
new Script(friends.match(/<script>([\s\S]*?)<\/script>/)?.[1]||'');
new Script(settings);
assert(friends.includes('id="bkFriendsBack"'),'Friend back link needs explicit handler');
assert(friends.includes('if(window.parent===window)return'),'Standalone friends page must use ordinary navigation');
assert(friends.includes('event.preventDefault()'),'Inline return must not navigate within iframe');
assert(friends.includes("window.parent.postMessage({type:'BAKEN_CLOSE_INLINE_FRIENDS'},location.origin)"),'Close event must be same-origin');
assert(settings.includes("event.origin!==location.origin||event.source!==frame.contentWindow"),'Parent must verify both origin and iframe source');
assert(settings.includes("event.data?.type!=='BAKEN_CLOSE_INLINE_FRIENDS'"),'Only permitted close message accepted');
assert(settings.includes("setFriendsVisible(false)"),'Close should hide iframe without reloading app');
assert(settings.includes("open.scrollIntoView({block:'nearest'})"),'Return to settings close control');
assert(friends.includes("credentials:'same-origin'"),'Friend auth route remains unchanged');
assert(fs.readFileSync('index.html','utf8').includes("const APP_VERSION='v1.04';"),'Do not change v1.04');
console.log('PASS: embedded friend return closes frame; standalone page and v1.04 unchanged');

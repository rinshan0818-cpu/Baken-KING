const assert=require('node:assert/strict');
const p=require('../friends-policy.js');
const alice={subject:'account_alice_123',verified:true};
const bob={subject:'account_bob_12345',verified:true};
const stranger={subject:'account_stranger_1',verified:true};
const unverified={...bob,verified:false};
const req=p.request(alice.subject,bob.subject,alice);
assert.equal(req.status,'pending');
assert.equal(p.canView(alice.subject,bob,[req]),false);
assert.equal(p.canView(alice.subject,alice,[]),true);
assert.throws(()=>p.request(alice.subject,bob.subject,bob),/Access denied/);
assert.throws(()=>p.respond(req,alice,true),/Access denied/);
assert.throws(()=>p.respond(req,unverified,true),/Access denied/);
const accepted=p.respond(req,bob,true);
assert.equal(p.canView(alice.subject,bob,[accepted]),true);
assert.equal(p.canView(bob.subject,alice,[accepted]),true);
assert.equal(p.canView(alice.subject,stranger,[accepted]),false);
assert.equal(p.canView(alice.subject,bob,[{...accepted,key:'spoofedxx'}]),false);
assert.throws(()=>p.revoke(accepted,stranger),/Access denied/);
const revoked=p.revoke(accepted,alice);
assert.equal(p.canView(alice.subject,bob,[revoked]),false);
assert.equal(p.canView(bob.subject,alice,[revoked]),false);
assert.equal(p.canView(alice.subject,bob,[p.respond(req,bob,false)]),false);
assert.throws(()=>p.canView(alice.subject,{subject:'account_bob_12345'},[accepted]),/Access denied/);
console.log('PASS: friend invitations require verified identity, recipient approval, and revocation');

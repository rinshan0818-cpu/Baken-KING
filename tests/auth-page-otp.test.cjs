const assert=require('node:assert/strict');
const fs=require('node:fs');
const html=fs.readFileSync('auth.html','utf8');
const script=html.match(/<script>([\s\S]*?)<\/script>/)?.[1];
assert(script,'Login page must retain its isolated script');
new (require('node:vm').Script)(script,{filename:'auth.html'});
for(const endpoint of ['/sign-in/email','/sign-up/email','/get-session','/sign-out','/email-otp/send-verification-otp','/email-otp/verify-email'])assert(html.includes(endpoint),endpoint+' missing');
assert(html.includes('emailVerified'),'Verification state must be shown');
assert(html.includes("searchParams.get('return')"),'Invite return link must be parsed safely');
assert(html.includes('friends\\.html\\?invite='),'Only friend invite return URL is allowed');
assert(html.includes("$('returnLink').href='./friends.html?invite='"),'Invite return URL must be local');
assert(html.includes('inputmode="numeric"'),'OTP input required');
assert(html.includes("clearFriendCache()"),'Logout must clear friend comparison cache');
assert(html.includes("user.id!==owner"),'Account switch must clear stale friend cache');
assert(!html.includes("localStorage.removeItem('keiba-demo-v1'"),'Auth must never modify local wager storage');
assert(!html.includes("localStorage.setItem('keiba-demo-v1'"),'Auth must never replace local wallet');
assert(!html.includes('sharing_snapshots'),'Auth must not write friend data directly');
console.log('PASS: independent account page syntax and OTP verification controls');

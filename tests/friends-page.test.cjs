const assert=require('node:assert/strict');
const fs=require('node:fs');
const {Script}=require('node:vm');
const html=fs.readFileSync('friends.html','utf8');
const script=html.match(/<script>([\s\S]*?)<\/script>/)?.[1];
assert(script,'Friend management script missing');
new Script(script,{filename:'friends.html'});
for(const endpoint of ['/api/sharing/profile','/api/sharing/connections','/api/sharing/invitations','/api/sharing/friends/','/api/sharing/summary/'])assert(html.includes(endpoint),endpoint+' missing');
for(const id of ['connect','register','copyId','copyInvite','invite','invitations','friends','comparison','connectionBadge'])assert(html.includes('id="'+id+'"'),id+' missing');
assert(html.includes('emailVerified!==true'),'Verified login guard required');
assert(html.includes('/api/sharing/me'),'Profile provisioning status must be checked before inviting');
assert(html.includes("searchParams.get('invite')"),'Friend invitation link should prefill recipient ID');
assert(html.includes("$('loginLink').href='./auth.html?return='"),'Invitation must survive navigation to login');
assert(html.includes("me.user.profile.displayName"),'Reconnect must reuse server profile display name');
assert(html.includes("encodeURIComponent(id)"),'Friend invite URL must safely encode identifier');
assert(!html.includes('準備中・先行画面'),'Obsolete preview label must be removed');
assert(html.includes('if(!profileReady)throw Error'),'Invitation must require explicit profile registration');
assert(html.includes('cachedId!==selectedFriendId'),'Do not show unrelated friend comparison after switching friends');
assert(html.includes("fetch('/api/auth/friends/'+route"),'Friend sharing must use the same-origin proxy');
assert(html.includes("credentials:'same-origin'"),'Friend sharing uses protected same-origin session cookies');
assert(!html.includes('Authorization:\'Bearer '),'Browser must not manage a sharing bearer token');
assert(html.includes("localStorage.setItem('baken-king-friend-score-v1'"),'Friend summary must be reflected into data tab');
assert(html.includes("cachedOwner!==user.id"),'Different accounts must not reuse a cached friend comparison');
assert(html.includes("baken-king-friend-score-friend-id-v1"),'Friend cache must record which friend is compared');
assert(html.includes("localStorage.removeItem('baken-king-friend-score-v1'"),'Unfriend must clear cached comparison');
assert(!html.includes("localStorage.setItem('keiba-demo-v1'"),'Friend page must not modify local wallet or tickets');
assert(!html.includes("localStorage.setItem('baken-king-test-state-v1'"),'Friend page must not modify test wallet');
assert(!html.includes('/api/account/backup'),'Friend management must not touch personal backups');
assert(html.includes('友達APIに接続できません'),'Unavailable sharing API status must be explicit');
console.log('PASS: friends page syntax, secured transport, nine metrics and unchanged local data');
